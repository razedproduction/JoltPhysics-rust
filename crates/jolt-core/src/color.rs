#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn u32_round_trip_and_layout() {
        let c = Color::new(1, 2, 3, 4);
        assert_eq!(Color::from_u32(c.uint32()), c);
        assert_eq!(c.uint32().to_ne_bytes(), [1, 2, 3, 4]);
        assert_eq!(std::mem::size_of::<Color>(), 4);
    }

    #[test]
    fn arithmetic() {
        assert_eq!(Color::WHITE * Color::new(128, 64, 0, 255), Color::new(127, 63, 0, 254));
        assert_eq!(Color::new(200, 100, 10, 7) * 0.5, Color::new(100, 50, 5, 7));
        assert_eq!(Color::WHITE.intensity(), 255);
        assert_eq!(Color::with_alpha(Color::RED, 3)[3], 3);
    }

    #[test]
    fn gradient_and_distinct() {
        assert_eq!(Color::green_red_gradient(-1.0), Color::GREEN);
        assert_eq!(Color::green_red_gradient(0.25), Color::rgb(127, 255, 0));
        assert_eq!(Color::green_red_gradient(0.75), Color::rgb(255, 127, 0));
        assert_eq!(Color::green_red_gradient(2.0), Color::RED);
        assert_eq!(Color::distinct_color(36), Color::distinct_color(0));
    }
}
