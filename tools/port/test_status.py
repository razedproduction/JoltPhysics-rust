#!/usr/bin/env python3
"""Track which C++ unit tests (UnitTests/**/*.cpp) have been ported to Rust.

Convention: a Rust file under `crates/` that ports tests from a C++ file says so with a marker
comment, e.g. `//! Port of UnitTests/Math/Vec3Tests.cpp`, and a C++
`TEST_CASE("TestVec3ConstructComponents")` from that file is ported as
`fn test_vec3_construct_components()` in one of the files carrying that marker. (Test names repeat
across C++ files, so matching is per file.) This script writes `port/TEST_STATUS.md`.

Usage:
    python tools/port/test_status.py            # regenerate port/TEST_STATUS.md, print summary
    python tools/port/test_status.py --name X   # print the Rust name for C++ test case X
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CPP_TESTS = ROOT / "UnitTests"
RUST_SRC = ROOT / "crates"
OUTPUT = ROOT / "port" / "TEST_STATUS.md"

SUITE_RE = re.compile(r'TEST_SUITE\s*\(\s*"([^"]+)"')
CASE_RE = re.compile(r'TEST_CASE\s*\(\s*"([^"]+)"')
RUST_FN_RE = re.compile(r"\bfn\s+([a-z0-9_]+)\s*\(")
MARKER_RE = re.compile(r"Port of (UnitTests/[A-Za-z0-9_/]+\.cpp)")


def to_snake(name: str) -> str:
    """TestVec3ConstructComponents -> test_vec3_construct_components, TestRayAABox -> test_ray_aa_box."""
    name = re.sub(r"[^A-Za-z0-9]+", "_", name)
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return re.sub(r"_+", "_", name).strip("_").lower()


def collect_cpp_tests():
    tests = []  # (relative file, suite, case)
    for path in sorted(CPP_TESTS.rglob("*.cpp")):
        suite = None
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if m := SUITE_RE.search(line):
                suite = m.group(1)
            elif m := CASE_RE.search(line):
                tests.append((path.relative_to(ROOT).as_posix(), suite or "", m.group(1)))
    return tests


def collect_rust_fns():
    """Map C++ test file (relative path) -> Rust fn names found in files carrying its marker."""
    fns = {}
    if RUST_SRC.exists():
        for path in RUST_SRC.rglob("*.rs"):
            text = path.read_text(encoding="utf-8", errors="replace")
            names = set(RUST_FN_RE.findall(text))
            for cpp in MARKER_RE.findall(text):
                fns.setdefault(cpp, set()).update(names)
    return fns


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--name", help="print the Rust test name for a C++ TEST_CASE name and exit")
    args = parser.parse_args()
    if args.name:
        print(to_snake(args.name))
        return 0

    tests = collect_cpp_tests()
    rust_fns = collect_rust_fns()

    by_file = {}
    for file, suite, case in tests:
        by_file.setdefault(file, []).append((suite, case))

    total_done = 0
    lines = [
        "# Unit test porting status",
        "",
        "Generated by `python tools/port/test_status.py` — do not edit by hand.",
        "A C++ `TEST_CASE(\"TestFooBar\")` from `UnitTests/X/Y.cpp` counts as ported when `fn test_foo_bar()` exists",
        "in a Rust file under `crates/` containing the marker `Port of UnitTests/X/Y.cpp`.",
        "",
    ]
    summary = ["| C++ file | Ported |", "|---|---|"]
    details = []
    for file, cases in by_file.items():
        ported = rust_fns.get(file, set())
        done = sum(1 for _, case in cases if to_snake(case) in ported)
        total_done += done
        summary.append(f"| `{file}` | {done}/{len(cases)} |")
        details += ["", f"## `{file}`", ""]
        for suite, case in cases:
            rust = to_snake(case)
            mark = "x" if rust in ported else " "
            details.append(f"- [{mark}] `{suite}::{case}` → `{rust}`")

    lines.append(f"**Total: {total_done}/{len(tests)}**")
    lines.append("")
    lines += summary + details
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{total_done}/{len(tests)} C++ test cases ported; wrote {OUTPUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
