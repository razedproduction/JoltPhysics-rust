use std::ops::{Index, IndexMut, Mul};

/// Class that holds an RGBA color with 8-bits per component
///
/// The C++ union with a `uint32` member is replaced by [`Color::from_u32`] / [`Color::uint32`], which use the same
/// (native endian) memory layout.
#[repr(C, align(4))]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct Color {
    /// Red channel
    pub r: u8,
    /// Green channel
    pub g: u8,
    /// Blue channel
    pub b: u8,
    /// Alpha channel
    pub a: u8,
}

impl Color {
    /// Construct from red, green, blue and alpha
    #[inline]
    pub const fn new(r: u8, g: u8, b: u8, a: u8) -> Self {
        Self { r, g, b, a }
    }

    /// Construct from red, green and blue, alpha = 255
    #[inline]
    pub const fn rgb(r: u8, g: u8, b: u8) -> Self {
        Self::new(r, g, b, 255)
    }

    /// Construct from the combined value for red, green, blue and alpha (C++ `Color(uint32)`)
    #[inline]
    pub const fn from_u32(color: u32) -> Self {
        let [r, g, b, a] = color.to_ne_bytes();
        Self { r, g, b, a }
    }

    /// Copy of `color` with a different alpha (C++ `Color(ColorArg, uint8)`)
    #[inline]
    pub const fn with_alpha(color: Color, alpha: u8) -> Self {
        Self::new(color.r, color.g, color.b, alpha)
    }

    /// Convert to uint32
    #[inline]
    pub const fn uint32(self) -> u32 {
        u32::from_ne_bytes([self.r, self.g, self.b, self.a])
    }

    /// Get grayscale intensity of color
    #[inline]
    pub const fn intensity(self) -> u8 {
        ((self.r as u32 * 54 + self.g as u32 * 183 + self.b as u32 * 19) >> 8) as u8
    }

    /// Get a visually distinct color
    pub fn distinct_color(index: i32) -> Color {
        debug_assert!(index >= 0);

        COLORS[index as usize % COLORS.len()]
    }

    /// Get a color value on the gradient from green through yellow to red
    /// @param value Value in the range [0, 1], 0 = green, 0.5 = yellow, 1 = red
    pub fn green_red_gradient(value: f32) -> Color {
        if value < 0.0 {
            Color::GREEN
        } else if value < 0.5 {
            Color::rgb((510.0 * value) as u8, 255, 0)
        } else if value < 1.0 {
            Color::rgb(255, (510.0 * (1.0 - value)) as u8, 0)
        } else {
            Color::RED
        }
    }

    // Predefined colors
    pub const BLACK: Color = Color::rgb(0, 0, 0);
    pub const DARK_RED: Color = Color::rgb(128, 0, 0);
    pub const RED: Color = Color::rgb(255, 0, 0);
    pub const DARK_GREEN: Color = Color::rgb(0, 128, 0);
    pub const GREEN: Color = Color::rgb(0, 255, 0);
    pub const DARK_BLUE: Color = Color::rgb(0, 0, 128);
    pub const BLUE: Color = Color::rgb(0, 0, 255);
    pub const YELLOW: Color = Color::rgb(255, 255, 0);
    pub const PURPLE: Color = Color::rgb(255, 0, 255);
    pub const CYAN: Color = Color::rgb(0, 255, 255);
    pub const ORANGE: Color = Color::rgb(255, 128, 0);
    pub const DARK_ORANGE: Color = Color::rgb(128, 64, 0);
    pub const GREY: Color = Color::rgb(128, 128, 128);
    pub const LIGHT_GREY: Color = Color::rgb(192, 192, 192);
    pub const WHITE: Color = Color::rgb(255, 255, 255);
}

/// Element access, 0 = red, 1 = green, 2 = blue, 3 = alpha
impl Index<usize> for Color {
    type Output = u8;

    #[inline]
    fn index(&self, idx: usize) -> &u8 {
        match idx {
            0 => &self.r,
            1 => &self.g,
            2 => &self.b,
            3 => &self.a,
            _ => panic!("color index {idx} out of range"),
        }
    }
}

/// Element access, 0 = red, 1 = green, 2 = blue, 3 = alpha
impl IndexMut<usize> for Color {
    #[inline]
    fn index_mut(&mut self, idx: usize) -> &mut u8 {
        match idx {
            0 => &mut self.r,
            1 => &mut self.g,
            2 => &mut self.b,
            3 => &mut self.a,
            _ => panic!("color index {idx} out of range"),
        }
    }
}

/// Multiply two colors
impl Mul for Color {
    type Output = Color;

    #[inline]
    fn mul(self, rhs: Color) -> Color {
        Color::new(
            ((self.r as u32 * rhs.r as u32) >> 8) as u8,
            ((self.g as u32 * rhs.g as u32) >> 8) as u8,
            ((self.b as u32 * rhs.b as u32) >> 8) as u8,
            ((self.a as u32 * rhs.a as u32) >> 8) as u8,
        )
    }
}

/// Multiply color with intensity in the range [0, 1]
impl Mul<f32> for Color {
    type Output = Color;

    #[inline]
    fn mul(self, intensity: f32) -> Color {
        Color::new(
            (self.r as f32 * intensity) as u8,
            (self.g as f32 * intensity) as u8,
            (self.b as f32 * intensity) as u8,
            self.a,
        )
    }
}

